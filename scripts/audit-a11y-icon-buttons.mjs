// First-pass audit: find icon-only buttons missing aria-label / title.
//
// A common WCAG 2.1 AA failure is icon-only buttons without an accessible
// name. This script does a regex pass over .tsx files to flag the most
// obvious cases — buttons whose visible content is a single Lucide-style
// icon with no aria-label, no title, and no surrounding text.
//
// Output is written to planning-docs/wcag-audit-icon-buttons.md so the
// findings can be tracked through the manual audit.
//
// Usage: node scripts/audit-a11y-icon-buttons.mjs
//
// False positives are expected — review each finding rather than mass-fixing.

import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SCAN_DIRS = ["client/src", "client-aac/src"];
const OUT_FILE = path.join(ROOT, "planning-docs", "wcag-audit-icon-buttons.md");

const offenders = [];

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === "dist" || entry.name === "build") continue;
      walk(p);
    } else if (entry.name.endsWith(".tsx")) {
      scanFile(p);
    }
  }
}

// Multiline match: a Button whose body contains a single self-closing
// PascalCase icon component and nothing else (whitespace allowed). Body
// can span lines. Does not match buttons with text or multiple children.
const RE = /<(Button|button)\b([^>]*?)>\s*<([A-Z][A-Za-z0-9]*)\b([^>/]*)\/>\s*<\/(?:Button|button)>/g;

function lineNumberOfIndex(src, idx) {
  let n = 1;
  for (let i = 0; i < idx; i++) if (src[i] === "\n") n++;
  return n;
}

function scanFile(filePath) {
  const src = fs.readFileSync(filePath, "utf8");
  RE.lastIndex = 0;
  let m;
  while ((m = RE.exec(src)) !== null) {
    const attrs = m[2];
    if (/aria-label\s*=/.test(attrs)) continue;
    if (/aria-labelledby\s*=/.test(attrs)) continue;
    if (/title\s*=/.test(attrs)) continue;
    const line = lineNumberOfIndex(src, m.index);
    const fullMatch = m[0].replace(/\s+/g, " ").trim();
    offenders.push({
      file: path.relative(ROOT, filePath).replace(/\\/g, "/"),
      line,
      icon: m[3],
      snippet: fullMatch.slice(0, 140),
    });
  }
}

for (const dir of SCAN_DIRS) walk(path.join(ROOT, dir));

const byFile = new Map();
for (const o of offenders) {
  if (!byFile.has(o.file)) byFile.set(o.file, []);
  byFile.get(o.file).push(o);
}

const today = new Date().toISOString().slice(0, 10);
const out = [];
out.push("# WCAG 2.1 AA Audit — Icon-only buttons missing aria-label");
out.push("");
out.push(`Generated by \`scripts/audit-a11y-icon-buttons.mjs\` on ${today}.`);
out.push("");
out.push(`**Total findings:** ${offenders.length} across ${byFile.size} files.`);
out.push("");
out.push("Each finding is an icon-only `<Button>` or `<button>` with no `aria-label`, `aria-labelledby`, or `title` attribute. Re-run the script after fixes; it should report fewer findings each pass. False positives (e.g. icon-plus-text on the next line) are expected — review each, don't mass-fix.");
out.push("");
out.push("Fix pattern: add `aria-label=\"<localized-action>\"` (or wrap in a Tooltip whose label resolves via `t()`).");
out.push("");

for (const [file, list] of [...byFile.entries()].sort()) {
  out.push(`## \`${file}\` (${list.length})`);
  out.push("");
  for (const o of list) {
    out.push(`- **L${o.line}** \`${o.icon}\` — \`${o.snippet}\``);
  }
  out.push("");
}

fs.writeFileSync(OUT_FILE, out.join("\n"));
console.log(`Wrote ${OUT_FILE}`);
console.log(`Total: ${offenders.length} findings across ${byFile.size} files.`);
