-- =============================================================================
-- Data backfill: move legacy biometric fields into biometric_data rows
-- =============================================================================
-- Runs BEFORE the drops so no data is lost. Each DO block iterates rows that
-- have legacy biometric fields populated but no biometric_data_id yet, creates
-- a biometric_data row, and links the parent row to it.

-- Users: face + voice embeddings
DO $$
DECLARE r RECORD;
DECLARE new_bd_id varchar;
BEGIN
  FOR r IN
    SELECT id, face_embedding, voice_embedding
    FROM users
    WHERE (face_embedding IS NOT NULL OR voice_embedding IS NOT NULL)
      AND biometric_data_id IS NULL
  LOOP
    INSERT INTO biometric_data (face_embedding, voice_embedding)
    VALUES (r.face_embedding, r.voice_embedding)
    RETURNING id INTO new_bd_id;
    UPDATE users SET biometric_data_id = new_bd_id WHERE id = r.id;
  END LOOP;
END $$;
--> statement-breakpoint

