-- Student contacts: embeddings + physical descriptors (description →
-- physical_description; face_image_data is dropped outright — it was unused
-- base64 legacy; new uploads write to biometric_data.face_image_url via S3).
DO $$
DECLARE r RECORD;
DECLARE new_bd_id varchar;
BEGIN
  FOR r IN
    SELECT id, face_embedding, voice_embedding, hair_color, estimated_age,
           estimated_sex, description, face_image_quality
    FROM student_contacts
    WHERE (face_embedding IS NOT NULL
           OR voice_embedding IS NOT NULL
           OR hair_color IS NOT NULL
           OR estimated_age IS NOT NULL
           OR estimated_sex IS NOT NULL
           OR description IS NOT NULL
           OR face_image_quality IS NOT NULL)
      AND biometric_data_id IS NULL
  LOOP
    INSERT INTO biometric_data (
      face_embedding, voice_embedding,
      hair_color, estimated_age, estimated_sex,
      physical_description, face_image_quality
    )
    VALUES (
      r.face_embedding, r.voice_embedding,
      r.hair_color, r.estimated_age, r.estimated_sex,
      r.description, r.face_image_quality
    )
    RETURNING id INTO new_bd_id;
    UPDATE student_contacts SET biometric_data_id = new_bd_id WHERE id = r.id;
  END LOOP;
END $$;
--> statement-breakpoint

